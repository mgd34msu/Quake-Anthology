typedef struct keyed {
  int key;
  int order;
} keyed;

static int by_key(const void *a, const void *b) {
  const keyed *x = a, *y = b;
  return (x->key > y->key) - (x->key < y->key);
}
static int by_key_ctx(const void *a, const void *b, void *ctx) {
  ++*(int *)ctx;
  return by_key(a, b);
}

/* [..].sort((a, b) => a.key - b.key) keeps equal keys in insertion order. */
static void sort_checks(void) {
  for (int count = 0; count < 300; count += 7) {
    keyed items[300];
    for (int i = 0; i < count; i++) {
      items[i].key = (i * 37 + 11) % 5;
      items[i].order = i;
    }
    qa_js_sort(items, (size_t)count, sizeof items[0], by_key);
    int ordered = 1;
    for (int i = 1; i < count; i++) {
      if (items[i - 1].key > items[i].key) ordered = 0;
      if (items[i - 1].key == items[i].key && items[i - 1].order > items[i].order) ordered = 0;
    }
    CHECK(ordered);
  }
  keyed many[5000];
  for (int i = 0; i < 5000; i++) {
    many[i].key = (int)(((unsigned)i * 2654435761u) % 97u);
    many[i].order = i;
  }
  int calls = 0;
  qa_js_stable_sort(many, 5000, sizeof many[0], by_key_ctx, &calls);
  int ordered = 1;
  for (int i = 1; i < 5000; i++) {
    if (many[i - 1].key > many[i].key) ordered = 0;
    if (many[i - 1].key == many[i].key && many[i - 1].order > many[i].order) ordered = 0;
  }
  CHECK(ordered);
  CHECK(calls > 0);
  /* bun: [3,1,2].sort((a,b)=>a-b) is [1,2,3]. */
  keyed small[3] = {{3, 0}, {1, 1}, {2, 2}};
  qa_js_sort(small, 3, sizeof small[0], by_key);
  CHECK(small[0].key == 1 && small[1].key == 2 && small[2].key == 3);
}

int main(void) {
  generated_checks();
  sort_checks();
  printf("test_js_semantics: %d checks, %d failures\n", checks, failures);
  return failures == 0 ? 0 : 1;
}
