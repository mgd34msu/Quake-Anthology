/* Same value, NaN equal to NaN, and -0 distinct from +0 (Object.is). */
static int same(double a, double b) {
  if (isnan(a) || isnan(b)) return isnan(a) && isnan(b);
  return a == b && signbit(a) == signbit(b);
}
#define SAME(actual, expected)                                                          \
  do {                                                                                  \
    double got_ = (actual), want_ = (expected);                                         \
    checks++;                                                                           \
    if (!same(got_, want_)) {                                                           \
      failures++;                                                                       \
      fprintf(stderr, "FAIL %s:%d: %s = %.17g, want %.17g\n", __FILE__, __LINE__, #actual, \
              got_, want_);                                                             \
    }                                                                                   \
  } while (0)
#define FIXED(value, digits, expected)                                                  \
  do {                                                                                  \
    char text_[QA_JS_TO_FIXED_CAPACITY];                                                \
    size_t length_ = qa_js_to_fixed((value), (digits), text_, sizeof text_);            \
    checks++;                                                                           \
    if (strcmp(text_, (expected)) != 0 || length_ != strlen(expected)) {                \
      failures++;                                                                       \
      fprintf(stderr, "FAIL %s:%d: toFixed(%s, %d) = \"%s\", want \"%s\"\n", __FILE__, __LINE__, \
              #value, (digits), text_, (expected));                                     \
    }                                                                                   \
  } while (0)

