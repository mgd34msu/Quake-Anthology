typedef struct seeded_random {
  uint32_t state;
} seeded_random;
static double next_random(seeded_random *random) {
  random->state += 0x6d2b79f5u;
  uint32_t value = random->state;
  value = (value ^ (value >> 15)) * (value | 1u);
  value ^= value + (value ^ (value >> 7)) * (value | 61u);
  return (double)(value ^ (value >> 14)) / 4294967296.0;
}
static size_t pick(seeded_random *random, size_t limit) { return (size_t)(next_random(random) * (double)limit); }

/* mutate(): returns a malloc'd mutant of `source`. */
static uint8_t *mutate(const uint8_t *source, size_t length, seeded_random *random, size_t *out_length) {
  uint8_t *bytes = malloc(length + 16);
  memcpy(bytes, source, length);
  switch (pick(random, 6)) {
    case 0:
      if (length > 0) {
        size_t at = pick(random, length);
        bytes[at] ^= (uint8_t)(1u << pick(random, 8));
      }
      break;
    case 1:
      for (size_t count = 1 + pick(random, 4); count > 0 && length > 0; count--) {
        size_t at = pick(random, length);
        bytes[at] = (uint8_t)pick(random, 256);
      }
      break;
    case 2:
      length = pick(random, length + 1);
      break;
    case 3: {
      size_t at = pick(random, length + 1), extra = 1 + pick(random, 8);
      uint8_t inserted[8];
      for (size_t i = 0; i < extra; i++) inserted[i] = (uint8_t)pick(random, 256);
      memmove(bytes + at + extra, bytes + at, length - at);
      memcpy(bytes + at, inserted, extra);
      length += extra;
      break;
    }
    case 4: {
      size_t at = pick(random, length + 1);
      size_t room = length - at < 8 ? length - at : 8;
      size_t cut = pick(random, room + 1);
      memmove(bytes + at, bytes + at + cut, length - at - cut);
      length -= cut;
      break;
    }
    default:
      if (length >= 4) {
        static const uint32_t words[5] = {0xffffffffu, 0x7fffffffu, 0x80000000u, 0, 0x00010000u};
        size_t at = pick(random, length - 3);
        uint32_t word = words[pick(random, 5)];
        for (int i = 0; i < 4; i++) bytes[at + (size_t)i] = (uint8_t)(word >> (8 * i));
      }
      break;
  }
  *out_length = length;
  return bytes;
}

typedef struct decode_job {
  const uint8_t *bytes;
  size_t length;
  bool save_image;
} decode_job;
static void decode_run(void *raw) {
  decode_job *job = raw;
  if (job->save_image) {
    qa_save_image_result result;
    memset(&result, 0, sizeof result);
    if (qa_decode_save_image(job->bytes, job->length, &result)) {
      qa_executable_recipe_free(&result.image.recipe);
      qa_save_image_result_free(&result);
    }
  } else {
    qa_save_value_free(qa_decode_checkpoint_value(job->bytes, job->length));
  }
}

static void run_mutations(uint32_t seed, int count, const uint8_t *valid, size_t length, bool save_image,
                          int want_accepted, int want_rejected) {
  seeded_random random = {seed};
  int accepted = 0, rejected = 0, foreign = 0;
  for (int index = 0; index < count; index++) {
    size_t mutant_length = 0;
    uint8_t *mutant = mutate(valid, length, &random, &mutant_length);
    decode_job job = {mutant, mutant_length, save_image};
    qa_caught_error caught;
    if (qa_try(decode_run, &job, &caught)) {
      accepted++;
    } else {
      rejected++;
      if (strcmp(caught.name, "TypeError") == 0) {
        foreign++;
        fprintf(stderr, "  seed %u mutant %d: %s: %s\n", seed, index, caught.name, caught.message);
      }
    }
    free(mutant);
  }
  if (accepted != want_accepted || rejected != want_rejected)
    fprintf(stderr, "  seed %u: accepted %d rejected %d (bun %d/%d)\n", seed, accepted, rejected, want_accepted,
            want_rejected);
  CHECK(foreign == 0);
  CHECK(rejected > 0);
  CHECK(accepted == want_accepted && rejected == want_rejected);
}

int main(void) {
  /* seeded mutants of a unified save either decode or fail with a typed error */
  qa_save_image_result result;
  memset(&result, 0, sizeof result);
  CHECK(qa_decode_save_image(SAVE_IMAGE, sizeof SAVE_IMAGE, &result));
  CHECK(result.image.frame.frame == 1);
  qa_executable_recipe_free(&result.image.recipe);
  qa_save_image_result_free(&result);
  run_mutations(1, 600, SAVE_IMAGE, sizeof SAVE_IMAGE, true, 29, 571);
  run_mutations(2, 600, SAVE_IMAGE, sizeof SAVE_IMAGE, true, 26, 574);
  run_mutations(3, 600, SAVE_IMAGE, sizeof SAVE_IMAGE, true, 23, 577);
  /* seeded mutants of a checkpoint value never escape as untyped failures */
  run_mutations(11, 800, CHECKPOINT_VALUE, sizeof CHECKPOINT_VALUE, false, 85, 715);
  run_mutations(12, 800, CHECKPOINT_VALUE, sizeof CHECKPOINT_VALUE, false, 91, 709);
  printf("%d checks, %d failures\n", checks, failures);
  return failures == 0 ? 0 : 1;
}
