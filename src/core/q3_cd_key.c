#include <string.h>

#include "qa/foundation/support.h"

/* CvarFlag.Archive from cvars/index.ts (not yet ported). */
#define QA_CVAR_FLAG_ARCHIVE 1

const char *qa_q3_key_build_name(qa_q3_key_build build) {
  return build == QA_Q3_KEY_BUILD_CLIENT ? "client" : "dedicated";
}

bool qa_q3_key_build_parse(const char *text, qa_q3_key_build *out) {
  if (strcmp(text, "client") == 0) {
    *out = QA_Q3_KEY_BUILD_CLIENT;
    return true;
  }
  if (strcmp(text, "dedicated") == 0) {
    *out = QA_Q3_KEY_BUILD_DEDICATED;
    return true;
  }
  return false;
}

bool qa_validate_q3_cd_key(const char *key, const char *checksum) {
  if (strlen(key) != 16) return false;
  if (checksum != NULL && strlen(checksum) != 2) return false;
  int sum = 0;
  for (int index = 0; index < 16; index++) {
    int character = (unsigned char)key[index];
    if (character >= 97 && character <= 122) character -= 32;
    if (strchr("237ABCDGHJLPRSTW", character) == NULL) return false;
    sum = (sum + character) & 255;
  }
  if (checksum == NULL) return true;
  char wanted[3];
  snprintf(wanted, sizeof wanted, "%02x", (unsigned)sum);
  for (int i = 0; i < 2; i++) {
    int given = (unsigned char)checksum[i];
    if (given >= 'A' && given <= 'Z') given += 32; /* toLowerCase, ASCII */
    if (given != (unsigned char)wanted[i]) return false;
  }
  return true;
}

void qa_q3_cd_key_state_init(qa_q3_cd_key_state *state,
                             qa_q3_mark_modified_fn mark_modified_flags,
                             void *cvars_ctx, qa_q3_key_build build) {
  memset(state->bytes, 0, sizeof state->bytes);
  state->mark_modified_flags = mark_modified_flags;
  state->cvars_ctx = cvars_ctx;
  state->build = build;
  if (build == QA_Q3_KEY_BUILD_CLIENT) {
    memset(state->bytes, 32, 32);
  } else {
    for (int index = 0; index < 9; index++) {
      state->bytes[index] = (uint8_t)(49 + index);
    }
  }
}

/* The TS private file(): the validated key as a zeroed 33-byte record,
 * or 0 (with out untouched) when the stored text is unusable. */
static int load_key_file(const qa_q3_cd_key_state *state,
                         const qa_q3_key_storage *storage, uint8_t out[33]) {
  const char *text = storage->load_text(storage->ctx, "q3key");
  if (text == NULL) return 0;
  char key[17];
  size_t key_length = strlen(text);
  if (key_length > 16) key_length = 16; /* text.slice(0, 16) */
  memcpy(key, text, key_length);
  key[key_length] = '\0';
  if (state->build == QA_Q3_KEY_BUILD_CLIENT &&
      !qa_validate_q3_cd_key(key, NULL)) {
    return 0;
  }
  memset(out, 0, 33);
  for (size_t index = 0; index < key_length && index < 16; index++) {
    uint8_t byte = (uint8_t)key[index];
    if (byte == 0) break;
    out[index] = byte;
  }
  return 1;
}

void qa_q3_cd_key_state_read_file(qa_q3_cd_key_state *state,
                                  const qa_q3_key_storage *storage) {
  uint8_t key[33];
  if (!load_key_file(state, storage, key)) {
    memset(state->bytes, 32, 16);
    state->bytes[16] = 0;
  } else {
    memcpy(state->bytes, key, 17);
  }
}

void qa_q3_cd_key_state_append_file(qa_q3_cd_key_state *state,
                                    const qa_q3_key_storage *storage) {
  uint8_t key[33];
  if (!load_key_file(state, storage, key)) {
    memset(state->bytes + 16, 32, 16);
    state->bytes[32] = 0;
    return;
  }
  int64_t end = -1;
  for (int64_t i = 16; i < 34; i++) {
    if (state->bytes[i] == 0) {
      end = i;
      break;
    }
  }
  int64_t length = 0;
  while (length < 33 && key[length] != 0) length++;
  length += 1; /* key.indexOf(0) + 1 */
  if (end < 0 || end + length > 34) {
    qa_range_error("CD key storage overflow");
  }
  memcpy(state->bytes + end, key, (size_t)length);
}

void qa_q3_cd_key_state_write_file(qa_q3_cd_key_state *state,
                                   const qa_q3_key_storage *storage,
                                   int64_t offset) {
  /* String.fromCharCode of the 16 bytes, then validated (which cuts
   * at any NUL byte, as the C string does here). */
  char key[17];
  memcpy(key, state->bytes + offset, 16);
  key[16] = '\0';
  if (!qa_validate_q3_cd_key(key, NULL)) return;
  char contents[256];
  snprintf(contents, sizeof contents,
           "%s\n// generated by quake, do not modify\r\n// Do not give this "
           "file to ANYONE.\r\n// id Software and Activision will NOT ask "
           "you to send this file to them.\r\n",
           key);
  storage->dump(storage->ctx, "q3key", contents);
}

void qa_q3_cd_key_state_read_authorization(const qa_q3_cd_key_state *state,
                                           uint8_t *destination,
                                           size_t destination_length) {
  if (destination_length < 33) {
    qa_range_error("CD key authorization requires 33 bytes");
  }
  memcpy(destination, state->bytes, 32);
  destination[32] = 0;
}

static size_t ui_offset(int64_t unique_key_result, const char *game_directory) {
  return unique_key_result == 1 && strlen(game_directory) != 0 ? 16 : 0;
}

void qa_q3_cd_key_state_read_ui(const qa_q3_cd_key_state *state,
                                int64_t unique_key_result,
                                const char *game_directory,
                                uint8_t *destination,
                                size_t destination_length,
                                const qa_q3_key_ui_writes *writes) {
  if (destination_length < 17) {
    qa_range_error("CD key UI destination requires 17 bytes");
  }
  size_t offset = ui_offset(unique_key_result, game_directory);
  if (writes == NULL) {
    memcpy(destination, state->bytes + offset, 16);
    destination[16] = 0;
  } else {
    writes->copy(writes->ctx, state->bytes + offset, 16);
    writes->set_byte(writes->ctx, 16, 0);
  }
}

void qa_q3_cd_key_state_write_ui(qa_q3_cd_key_state *state,
                                 int64_t unique_key_result,
                                 const char *game_directory,
                                 const uint8_t *source,
                                 size_t source_length) {
  if (source_length < 16) {
    qa_range_error("CD key UI source requires 16 bytes");
  }
  size_t offset = ui_offset(unique_key_result, game_directory);
  memcpy(state->bytes + offset, source, 16);
  if (offset == 16) state->bytes[32] = 0;
  if (state->mark_modified_flags != NULL) {
    state->mark_modified_flags(state->cvars_ctx, QA_CVAR_FLAG_ARCHIVE);
  }
}
