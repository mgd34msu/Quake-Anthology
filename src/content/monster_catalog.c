const qa_monster_catalog_source *qa_monster_catalog_sources(size_t *count)
{
    if (count) *count = sizeof(sources) / sizeof(*sources);
    return sources;
}

const qa_monster_catalog_source *qa_monster_catalog_source_find(const char *provider)
{
    for (size_t i = 0; provider && i < sizeof(sources) / sizeof(*sources); ++i)
        if (!strcmp(sources[i].provider, provider)) return sources + i;
    return NULL;
}

const qa_monster_catalog_creature *qa_monster_catalog_creature_find(
    const qa_monster_catalog_source *source, const char *classname)
{
    for (size_t i = 0; source && classname && i < source->creature_count; ++i)
        if (!strcmp(source->creatures[i].classname, classname)) return source->creatures + i;
    return NULL;
}

const qa_monster_catalog_slot *qa_monster_catalog_slots(qa_game_family family, size_t *count)
{
    if (count) *count = family == QA_GAME_Q1 ? sizeof(slots_q1) / sizeof(*slots_q1) :
        family == QA_GAME_Q2 ? sizeof(slots_q2) / sizeof(*slots_q2) : 0;
    return family == QA_GAME_Q1 ? slots_q1 : family == QA_GAME_Q2 ? slots_q2 : NULL;
}

const qa_monster_catalog_creature *qa_monster_catalog_default(qa_game_family authored,
    const qa_monster_catalog_source *source, const char *classname)
{
    if (!source || !classname) return NULL;
    size_t count;
    const qa_monster_catalog_slot *slots = qa_monster_catalog_slots(authored, &count);
    const qa_monster_catalog_slot *slot = NULL;
    for (size_t i = 0; i < count; ++i)
        if (!strcmp(slots[i].classname, classname)) { slot = slots + i; break; }
    if (!slot) return NULL;
    const char *target;
    if (authored == QA_GAME_Q2 && source->family == QA_GAME_Q1 && !strcmp(classname, "monster_parasite")) target = "monster_dog";
    else if (authored == QA_GAME_Q1 && source->family == QA_GAME_Q2 && !strcmp(classname, "monster_dog")) target = "monster_parasite";
    else if (slot->role == QA_MONSTER_BOSS || slot->role == QA_MONSTER_SPECIAL) return NULL;
    else if (source->family == authored && qa_monster_catalog_creature_find(source, classname)) target = classname;
    else {
        static const char *const preferred_q1[] = {"monster_army", "monster_enforcer", "monster_demon1", "monster_demon1", "monster_ogre", "monster_shalrath", "monster_shalrath", "monster_hell_knight", "monster_shambler", "monster_wizard", "monster_fish"};
        static const char *const preferred_q2[] = {"monster_soldier", "monster_infantry", "monster_berserk", "monster_mutant", "monster_gunner", "monster_chick", "monster_gladiator", "monster_brain", "monster_tank", "monster_flyer", "monster_flipper"};
        target = source->family == QA_GAME_Q1 ? preferred_q1[slot->role] : preferred_q2[slot->role];
    }
    return qa_monster_catalog_creature_find(source, target);
}
