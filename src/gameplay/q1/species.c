const q1_species *q1_species_find(const char *classname) {
    for (size_t i = 0; i < sizeof(species) / sizeof(*species); ++i)
        if (!strcmp(classname, q1_runtime_name_text(species[i].classname)))
            return &species[i];
    return NULL;
}

const q1_species *q1_species_named(q1_runtime_name classname) {
    for (size_t i = 0; i < sizeof(species) / sizeof(*species); ++i)
        if (classname == species[i].classname)
            return &species[i];
    return NULL;
}
