static const original_symbol *symbols(q2_original_symbol_kind kind, size_t *count)
{
    switch (kind) {
    case Q2_ORIGINAL_ITEM:
        *count = sizeof(item_symbols) / sizeof(item_symbols[0]);
        return item_symbols;
    case Q2_ORIGINAL_FUNCTION:
        *count = sizeof(function_symbols) / sizeof(function_symbols[0]);
        return function_symbols;
    case Q2_ORIGINAL_MOVE:
        *count = sizeof(move_symbols) / sizeof(move_symbols[0]);
        return move_symbols;
    }
    *count = 0;
    return NULL;
}

bool q2_original_symbol_encode(q2_original_symbol_kind kind, qa_q2_product product,
    const char *name, int32_t *value, qa_error *error)
{
    size_t count;
    const original_symbol *rows = symbols(kind, &count);
    if (!value || !rows || (unsigned)product > QA_Q2_ROGUE) {
        qa_error_set(error, QA_ERROR_ARGUMENT, 0, "Invalid original Q2 symbol domain");
        return false;
    }
    if (!name || !*name) {
        *value = kind == Q2_ORIGINAL_ITEM ? -1 : 0;
        return true;
    }
    size_t low = 0, high = count;
    while (low < high) {
        size_t middle = low + (high - low) / 2;
        int order = strcmp(rows[middle].name, name);
        if (order < 0) low = middle + 1;
        else high = middle;
    }
    if (low == count || strcmp(rows[low].name, name) ||
        !(rows[low].products & (1u << (unsigned)product))) {
        qa_error_set(error, QA_ERROR_UNSUPPORTED, 0,
            "Original Q2 symbol has no proved installed identity: %s", name);
        return false;
    }
    *value = rows[low].values[product];
    return true;
}

const char *q2_original_symbol_next(q2_original_symbol_kind kind, qa_q2_product product,
    int32_t value, const char *previous)
{
    size_t count;
    const original_symbol *rows = symbols(kind, &count);
    if (!rows || (unsigned)product > QA_Q2_ROGUE ||
        value == (kind == Q2_ORIGINAL_ITEM ? -1 : 0)) return NULL;
    bool reached = previous == NULL;
    for (size_t i = 0; i < count; ++i) {
        const original_symbol *row = rows + i;
        if (!reached) {
            reached = !strcmp(previous, row->name);
            continue;
        }
        if ((row->products & (1u << (unsigned)product)) && row->values[product] == value)
            return row->name;
    }
    return NULL;
}

size_t q2_original_item_count(qa_q2_product product)
{
    static const size_t counts[] = {42, 48, 62};
    return (unsigned)product <= QA_Q2_ROGUE ? counts[product] : 0;
}

const q2_original_library *q2_original_library_for(qa_q2_product product)
{
    return product == QA_Q2_XATRIX ? libraries :
        product == QA_Q2_ROGUE ? libraries + 1 : NULL;
}
