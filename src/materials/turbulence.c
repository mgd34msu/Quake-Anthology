double qa_source_turbulence(double phase, qa_turbulence_profile profile) {
  /* Math.trunc(...) & 255 is JS ToInt32 then mask; entry always exists. */
  double value = turbulence[qa_mat_to_int32(phase * 256 / (2 * acos(-1.0))) & 255];
  return profile == QA_TURBULENCE_Q1 ? value : qa_mat_f(value * 0.5);
}
