qa_native_q2_import_kind qa_native_q2_import_dispatch(qa_native_profile profile,uint32_t slot)
{
    switch (profile) {
    case QA_NATIVE_Q2_GAME_API3: return slot<COUNT(q2_imports)?q2_imports[slot].dispatch:QA_NATIVE_Q2_IMPORT_NONE;
    case QA_NATIVE_Q2_GAME_API2023: return slot<COUNT(rr_game_imports)?rr_game_imports[slot].dispatch:QA_NATIVE_Q2_IMPORT_NONE;
    case QA_NATIVE_Q2_CGAME_API2023: return slot<COUNT(rr_cgame_imports)?rr_cgame_imports[slot].dispatch:QA_NATIVE_Q2_IMPORT_NONE;
    default: return QA_NATIVE_Q2_IMPORT_NONE;
    }
}

bool native_profile_accepts(const native_profile_spec *profile, const qa_native_image_info *image,
                            qa_error *error) {
    if (!profile || !image)
        return native_fail(error, QA_ERROR_ARGUMENT, 0,
                           "native profile and image metadata are required");
    switch (profile->profile) {
    case QA_NATIVE_Q2_GAME_API3:
        if (image->target.arch == QA_NATIVE_ARCH_I386 ||
            (image->format == QA_NATIVE_IMAGE_ELF64 && image->target.arch == QA_NATIVE_ARCH_X86_64))
            return true;
        return native_fail(error, QA_ERROR_UNSUPPORTED, 0,
                           "Q2 API 3 requires an i386 image or a native x86-64 ELF rebuild");
    case QA_NATIVE_Q2_GAME_API2023:
    case QA_NATIVE_Q2_CGAME_API2023:
        if (image->target.arch == QA_NATIVE_ARCH_X86_64 &&
            (image->format == QA_NATIVE_IMAGE_PE32_PLUS || image->format == QA_NATIVE_IMAGE_ELF64))
            return true;
        return native_fail(error, QA_ERROR_UNSUPPORTED, 0,
                           "Q2 API 2023 requires an x86-64 PE or ELF image");
    case QA_NATIVE_Q3_VMMAIN:
        if (image->target.arch == QA_NATIVE_ARCH_I386 &&
            (image->format == QA_NATIVE_IMAGE_PE32 || image->format == QA_NATIVE_IMAGE_ELF32))
            return true;
        return native_fail(error, QA_ERROR_UNSUPPORTED, 0,
                           "Q3 1.32 native vmMain requires an i386 PE or ELF image");
    case QA_NATIVE_QUAKE_LIVE_GAME_API10:
        if ((image->target.arch == QA_NATIVE_ARCH_I386 && image->format == QA_NATIVE_IMAGE_ELF32) ||
            (image->target.arch == QA_NATIVE_ARCH_X86_64 && image->format == QA_NATIVE_IMAGE_ELF64))
            return true;
        return native_fail(error, QA_ERROR_UNSUPPORTED, 0,
                           "Quake Live API 10 requires an i386 or x86-64 ELF image");
    }
    return native_fail(error, QA_ERROR_ARGUMENT, 0, "unknown native profile");
}

static bool write_pointer(void *table, size_t offset, uint64_t pointer, size_t width) {
    if (width == 4) qa_store_u32le((uint8_t *)table + offset, (uint32_t)pointer);
    else qa_store_u64le((uint8_t *)table + offset, pointer);
    return true;
}

static size_t q2_entry_offset(const qa_native_instance *instance, uint32_t slot) {
    size_t pointer_bytes = instance->module->info.image.target.pointer_bytes;
    size_t offset = native_align(sizeof(int32_t), pointer_bytes);
    if (instance->module->info.profile != QA_NATIVE_Q2_GAME_API2023 || slot < 19)
        return offset + (size_t)slot * pointer_bytes;
    offset += 19u * pointer_bytes;
    offset += pointer_bytes * 2u + sizeof(uint32_t) * 3u;
    offset = native_align(offset, pointer_bytes);
    return offset + (size_t)(slot - 19u) * pointer_bytes;
}

static bool read_pointer(const qa_native_instance *instance, qa_native_address address,
    qa_native_address *out, qa_error *error) {
    uint8_t pointer[8]; size_t width = instance->module->info.image.target.pointer_bytes;
    if (!qa_native_read(instance, address, pointer, width, error))
        return false;
    *out = width == 4 ? qa_load_u32le(pointer) : qa_load_u64le(pointer);
    return true;
}

static bool publish_import_table(qa_native_instance *instance, qa_error *error)
{
    return qa_native_guest_allocate(instance->guest, instance->import_table_bytes,
        INT32_C(0x4e494d50), &instance->import_table_address, error) &&
        qa_native_guest_write(instance->guest, instance->import_table_address,
            (qa_bytes){instance->import_table, instance->import_table_bytes}, error);
}

bool native_profile_restore_tables(qa_native_instance *instance, qa_error *error)
{
    const native_profile_spec *profile = native_profile(instance->module->info.profile);
    if (!profile->q2_table) return true;
    int32_t api;
    if (!qa_native_read(instance, instance->export_table, &api, sizeof(api), error)) return false;
    if (api != (int32_t)profile->api_version)
        return native_fail(error, QA_ERROR_FORMAT, instance->export_table,
                           "restored native Q2 SDK API differs from its actual profile");
    if (profile->import_prefix) {
        uint8_t actual[16], expected[16] = {0};
        qa_store_u32le(expected, instance->options.tick_rate);
        qa_store_f32le(expected + 4, instance->options.frame_seconds);
        qa_store_u32le(expected + 8, instance->options.frame_milliseconds);
        if (profile->import_prefix != sizeof(actual) ||
            !qa_native_read(instance, instance->import_table_address, actual, sizeof(actual), error))
            return false;
        if (memcmp(actual, expected, sizeof(actual)))
            return native_fail(error, QA_ERROR_FORMAT, instance->import_table_address,
                               "restored native Q2 SDK clock differs from its actual declaration");
    }
    size_t width = instance->module->info.image.target.pointer_bytes;
    for (size_t i = 0; i < instance->import_count; ++i) {
        size_t offset = profile->import_prefix + i * width;
        qa_native_address address;
        if (offset > UINT64_MAX - instance->import_table_address)
            return native_fail(error, QA_ERROR_FORMAT, i, "restored native SDK import address overflows");
        if (!read_pointer(instance, instance->import_table_address + offset, &address, error)) return false;
        if (address != instance->imports[i].guest_address)
            return native_fail(error, QA_ERROR_FORMAT, i,
                               "restored native Q2 SDK import lost its retained callback");
    }
    for (size_t i = 0; i < instance->entry_count; ++i) {
        const native_entry_binding *entry = instance->entries + i;
        size_t offset = q2_entry_offset(instance, entry->spec.slot);
        qa_native_address address;
        if (offset > UINT64_MAX - instance->export_table)
            return native_fail(error, QA_ERROR_FORMAT, i, "restored native SDK export address overflows");
        if (!read_pointer(instance, instance->export_table + offset, &address, error)) return false;
        if (address != entry->address)
            return native_fail(error, QA_ERROR_FORMAT, entry->spec.slot,
                               "restored native Q2 SDK entry differs from its retained source table");
    }
    qa_native_entity_table saved = instance->entities;
    if (!native_profile_refresh_entities(instance, error)) return false;
    if (saved.base != instance->entities.base || saved.stride != instance->entities.stride ||
        saved.count != instance->entities.count || saved.capacity != instance->entities.capacity)
        return native_fail(error, QA_ERROR_FORMAT, instance->export_table,
                           "restored native Q2 entity extent differs from its retained SDK table");
    return true;
}

static bool bind_q2_table(qa_native_instance *instance, const native_profile_spec *profile,
                          qa_error *error) {
    size_t pointer_bytes = instance->module->info.image.target.pointer_bytes;
    size_t pointer_region;
    if (!native_size_multiply(profile->import_count, pointer_bytes, &pointer_region) ||
        !native_size_add(profile->import_prefix, pointer_region, &instance->import_table_bytes))
        return native_fail(error, QA_ERROR_MEMORY, 0, "native import table size overflow");
    instance->import_table = calloc(1, instance->import_table_bytes);
    instance->imports = calloc(profile->import_count, sizeof(*instance->imports));
    if (!instance->import_table || (profile->import_count && !instance->imports))
        return native_fail(error, QA_ERROR_MEMORY, 0, "allocating native import table");
    instance->import_count = profile->import_count;
    if (profile->import_prefix) {
        memcpy(instance->import_table, &instance->options.tick_rate,
               sizeof(instance->options.tick_rate));
        memcpy((uint8_t *)instance->import_table + 4, &instance->options.frame_seconds,
               sizeof(instance->options.frame_seconds));
        memcpy((uint8_t *)instance->import_table + 8, &instance->options.frame_milliseconds,
               sizeof(instance->options.frame_milliseconds));
    }
    for (size_t index = 0; index < profile->import_count; ++index) {
        if (!native_import_bind(&instance->imports[index], instance,
                                &profile->imports[index], error)) return false;
        uint64_t address = instance->imports[index].guest_address;
        write_pointer(instance->import_table, profile->import_prefix + index * pointer_bytes, address, pointer_bytes);
    }
    if (!publish_import_table(instance, error)) return false;
    qa_native_address get_api;
    if (!qa_native_export(instance, profile->entry_export, &get_api, error))
        return false;
    qa_native_type get_parameters[] = {TYPE(QA_NATIVE_ADDRESS)};
    qa_native_signature get_signature = {.abi = instance->module->info.image.target.abi,
                                         .parameters = get_parameters,
                                         .parameter_count = 1,
                                         .result = TYPE(QA_NATIVE_ADDRESS)};
    qa_native_value argument = {.type = QA_NATIVE_ADDRESS,
                                .as.address = instance->import_table_address};
    qa_native_value result = {0};
    bool ok =
        native_process_invoke(instance, get_api, &get_signature, &argument, 1, &result, error);
    if (!ok)
        return false;
    if (!result.as.address)
        return native_fail(error, QA_ERROR_FORMAT, 0, "native Q2 API returned a null export table");
    instance->export_table = result.as.address;
    int32_t api_version;
    if (!qa_native_read(instance, instance->export_table, &api_version, sizeof(api_version), error))
        return false;
    if (api_version != (int32_t)profile->api_version) {
        qa_error_set(error, QA_ERROR_UNSUPPORTED, 0, "native Q2 module reports API %d; expected %u",
                     api_version, profile->api_version);
        return false;
    }
    instance->entries = calloc(profile->entry_count, sizeof(*instance->entries));
    if (profile->entry_count && !instance->entries)
        return native_fail(error, QA_ERROR_MEMORY, 0, "allocating native export bindings");
    instance->entry_count = profile->entry_count;
    for (size_t index = 0; index < profile->entry_count; ++index) {
        native_entry_binding *binding = &instance->entries[index];
        binding->spec = profile->entries[index];
        binding->spec.signature.abi = instance->module->info.image.target.abi;
        qa_native_address at =
            instance->export_table + q2_entry_offset(instance, binding->spec.slot);
        if (!read_pointer(instance, at, &binding->address, error))
            return false;
        if (!binding->address && !binding->spec.optional) {
            qa_error_set(error, QA_ERROR_FORMAT, binding->spec.slot, "native Q2 export %s is null",
                         binding->spec.name);
            return false;
        }
    }
    return native_profile_refresh_entities(instance, error);
}

static bool bind_q3(qa_native_instance *instance, const native_profile_spec *profile,
                    qa_error *error) {
    qa_native_address dll_entry, vm_main;
    if (!qa_native_export(instance, "dllEntry", &dll_entry, error) ||
        !qa_native_export(instance, "vmMain", &vm_main, error))
        return false;
    qa_native_type parameter[] = {TYPE(QA_NATIVE_ADDRESS)};
    qa_native_signature signature = {.abi = instance->module->info.image.target.abi,
                                     .parameters = parameter,
                                     .parameter_count = 1,
                                     .result = TYPE(QA_NATIVE_VOID)};
    qa_native_value argument = {.type = QA_NATIVE_ADDRESS};
    if (!native_process_q3_bind(instance, &argument.as.address, error)) return false;
    bool ok =
        native_process_invoke(instance, dll_entry, &signature, &argument, 1, NULL, error);
    if (!ok)
        return false;
    instance->entries = calloc(1, sizeof(*instance->entries));
    if (!instance->entries)
        return native_fail(error, QA_ERROR_MEMORY, 0, "allocating native Q3 entry binding");
    instance->entry_count = 1;
    instance->entries[0].spec = profile->entries[0];
    instance->entries[0].spec.signature.abi = instance->module->info.image.target.abi;
    instance->entries[0].address = vm_main;
    return true;
}

static bool bind_ql(qa_native_instance *instance, const native_profile_spec *profile,
                    qa_error *error) {
    enum { QL_IMPORT_SLOTS = 206 };
    size_t pointer_bytes = instance->module->info.image.target.pointer_bytes;
    if (!native_size_multiply(QL_IMPORT_SLOTS, pointer_bytes, &instance->import_table_bytes))
        return native_fail(error, QA_ERROR_MEMORY, 0, "Quake Live import table size overflow");
    instance->import_table = calloc(1, instance->import_table_bytes);
    instance->imports = calloc(profile->import_count, sizeof(*instance->imports));
    if (!instance->import_table || !instance->imports)
        return native_fail(error, QA_ERROR_MEMORY, 0, "allocating Quake Live import table");
    instance->import_count = profile->import_count;
    for (size_t index = 0; index < profile->import_count; ++index) {
        const native_signature_spec *spec = &profile->imports[index];
        if (spec->slot >= QL_IMPORT_SLOTS)
            return native_fail(error, QA_ERROR_FORMAT, spec->slot,
                               "Quake Live import slot is outside API 10");
        if (!native_import_bind(&instance->imports[index], instance, spec, error))
            return false;
        write_pointer(instance->import_table, (size_t)spec->slot * pointer_bytes,
            instance->imports[index].guest_address, pointer_bytes);
    }
    if (!publish_import_table(instance, error)) return false;

    qa_native_address dll_entry;
    if (!qa_native_export(instance, profile->entry_export, &dll_entry, error))
        return false;
    qa_native_address exports = 0;
    int32_t api_version = 0;
    qa_native_type parameters[] = {TYPE(QA_NATIVE_ADDRESS), TYPE(QA_NATIVE_ADDRESS),
                                   TYPE(QA_NATIVE_ADDRESS)};
    qa_native_signature signature = {.abi = instance->module->info.image.target.abi,
                                     .parameters = parameters,
                                     .parameter_count = COUNT(parameters),
                                     .result = TYPE(QA_NATIVE_VOID)};
    qa_native_value arguments[] = {
        {.type = QA_NATIVE_ADDRESS},
        {.type = QA_NATIVE_ADDRESS,
         .as.address = instance->import_table_address},
        {.type = QA_NATIVE_ADDRESS}};
    uint64_t scratch = 0;
    if (!qa_native_guest_allocate(instance->guest, pointer_bytes + 4, INT32_C(0x4e414249), &scratch, error)) return false;
    arguments[0].as.address = scratch; arguments[2].as.address = scratch + pointer_bytes;
    bool ok = native_process_invoke(instance, dll_entry, &signature, arguments,
                              COUNT(arguments), NULL, error);
    if (scratch) {
        qa_native_address actual_exports = 0;
        if (ok) ok = read_pointer(instance, scratch, &actual_exports, error) &&
            qa_native_read(instance, scratch + pointer_bytes, &api_version, 4, error);
        exports = actual_exports;
        qa_error cleanup = {0};
        if (!qa_native_guest_free(instance->guest, scratch, &cleanup) && ok) { if (error) *error = cleanup; ok = false; }
    }
    if (!ok)
        return false;
    if (api_version != (int32_t)profile->api_version) {
        qa_error_set(error, QA_ERROR_UNSUPPORTED, 0,
                     "Quake Live module reports API %d; expected %u", api_version,
                     profile->api_version);
        return false;
    }
    if (!exports)
        return native_fail(error, QA_ERROR_FORMAT, 0,
                           "Quake Live dllEntry returned a null export table");
    instance->export_table = exports;
    instance->entries = calloc(profile->entry_count, sizeof(*instance->entries));
    if (!instance->entries)
        return native_fail(error, QA_ERROR_MEMORY, 0, "allocating Quake Live export bindings");
    instance->entry_count = profile->entry_count;
    for (size_t index = 0; index < profile->entry_count; ++index) {
        native_entry_binding *binding = &instance->entries[index];
        binding->spec = profile->entries[index];
        binding->spec.signature.abi = instance->module->info.image.target.abi;
        qa_native_address at =
            instance->export_table + (uint64_t)binding->spec.slot * pointer_bytes;
        if (!read_pointer(instance, at, &binding->address, error))
            return false;
        if (!binding->address) {
            qa_error_set(error, QA_ERROR_FORMAT, binding->spec.slot, "Quake Live export %s is null",
                         binding->spec.name);
            return false;
        }
    }
    return true;
}

bool native_profile_bind(qa_native_instance *instance, qa_error *error) {
    const native_profile_spec *profile = native_profile(instance->module->info.profile);
    if (!profile)
        return native_fail(error, QA_ERROR_ARGUMENT, 0, "unknown native module profile");
    if (profile->q2_table)
        return bind_q2_table(instance, profile, error);
    if (profile->q3_vm)
        return bind_q3(instance, profile, error);
    if (profile->quake_live)
        return bind_ql(instance, profile, error);
    return native_fail(error, QA_ERROR_ARGUMENT, 0, "native profile has no binding strategy");
}

bool native_profile_prepare_tables(qa_native_instance *instance, qa_error *error) {
    const native_profile_spec *profile =
        instance ? native_profile(instance->module->info.profile) : NULL;
    if (!profile)
        return native_fail(error, QA_ERROR_ARGUMENT, 0, "native process profile is invalid");
    instance->entries = calloc(profile->entry_count, sizeof(*instance->entries));
    if (profile->entry_count && !instance->entries)
        return native_fail(error, QA_ERROR_MEMORY, 0,
                           "allocating native process entry descriptions");
    instance->entry_count = profile->entry_count;
    for (size_t index = 0; index < profile->entry_count; ++index) {
        instance->entries[index].spec = profile->entries[index];
        instance->entries[index].spec.signature.abi = instance->module->info.image.target.abi;
    }
    return true;
}

void native_profile_unbind(qa_native_instance *instance) {
    if (!instance)
        return;
    for (size_t index = 0; index < instance->import_count; ++index)
        native_import_unbind(&instance->imports[index]);
    free(instance->entries);
    free(instance->imports);
    free(instance->import_table);
    instance->entries = NULL;
    instance->imports = NULL;
    instance->import_table = NULL;
    instance->entry_count = instance->import_count = 0;
    instance->import_table_bytes = 0;
    instance->export_table = 0;
}

const native_entry_binding *native_entry(const qa_native_instance *instance, const char *name) {
    if (!instance || !name)
        return NULL;
    for (size_t index = 0; index < instance->entry_count; ++index)
        if (!strcmp(instance->entries[index].spec.name, name))
            return &instance->entries[index];
    return NULL;
}

bool native_profile_refresh_entities(qa_native_instance *instance, qa_error *error) {
    qa_native_profile profile = instance->module->info.profile;
    if (profile == QA_NATIVE_Q2_CGAME_API2023 || profile == QA_NATIVE_Q3_VMMAIN ||
        profile == QA_NATIVE_QUAKE_LIVE_GAME_API10)
        return true;
    if (!instance->export_table)
        return native_fail(error, QA_ERROR_ARGUMENT, 0, "native Q2 export table is unavailable");
    size_t pointer_bytes = instance->module->info.image.target.pointer_bytes;
    size_t fields = native_align(sizeof(int32_t), pointer_bytes);
    fields += (profile == QA_NATIVE_Q2_GAME_API3 ? 15u : 19u) * pointer_bytes;
    qa_native_entity_table table = {0};
    if (!read_pointer(instance, instance->export_table + fields, &table.base, error))
        return false;
    fields += pointer_bytes;
    if (profile == QA_NATIVE_Q2_GAME_API3) {
        int32_t stride, count, capacity;
        if (!qa_native_read(instance, instance->export_table + fields, &stride, sizeof(stride), error) ||
            !qa_native_read(instance, instance->export_table + fields + 4u, &count, sizeof(count),
                                error) ||
            !qa_native_read(instance, instance->export_table + fields + 8u, &capacity, sizeof(capacity),
                                error))
            return false;
        if (stride < 0 || count < 0 || capacity < 0) {
            return native_fail(error, QA_ERROR_FORMAT, fields,
                               "native Q2 entity metadata is negative");
        }
        table.stride = (size_t)stride;
        table.count = (uint32_t)count;
        table.capacity = (uint32_t)capacity;
    } else {
        uint64_t stride;
        if (!qa_native_read(instance, instance->export_table + fields, &stride, sizeof(stride), error) ||
            !qa_native_read(instance, instance->export_table + fields + 8u, &table.count,
                                sizeof(table.count), error) ||
            !qa_native_read(instance, instance->export_table + fields + 12u, &table.capacity,
                                sizeof(table.capacity), error))
            return false;
#if SIZE_MAX < UINT64_MAX
        if (stride > (uint64_t)SIZE_MAX)
            return native_fail(error, QA_ERROR_FORMAT, fields,
                               "native Q2 entity stride exceeds the host");
#endif
        table.stride = (size_t)stride;
    }
    qa_error publication = {0};
    if (!native_entity_table_store(instance, table, &publication)) {
        if (publication.code == QA_ERROR_ARGUMENT)
            return native_fail(error, QA_ERROR_FORMAT, fields,
                               "invalid native Q2 entity table metadata");
        if (publication.code == QA_ERROR_MEMORY)
            return native_fail(error, QA_ERROR_MEMORY, 0,
                               "allocating native source slot bindings");
        if (error) *error = publication;
        return false;
    }
    return true;
}

