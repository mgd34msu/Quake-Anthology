#define COUNT(a) (sizeof(a) / sizeof((a)[0]))
#define TYPE(k) {.kind = (k), .count = 1}
#define ARRAY(k, n) {.kind = (k), .count = (n)}
#define STRUCT(members)                                                                            \
    {.kind = QA_NATIVE_BYTES, .fields = (members), .field_count = COUNT(members), .count = 1}
#define PARAMS(...)                                                                                \
    (const qa_native_type[]) { __VA_ARGS__ }
#define SPEC0(label, index, handler, return_type)                                                           \
    {.name = (label),                                                                              \
     .signature = {.abi = QA_NATIVE_ABI_CDECL_I386,                                                \
                   .parameters = NULL,                                                             \
                   .parameter_count = 0,                                                           \
                   .result = return_type},                                                         \
     .slot = (index), .dispatch = (handler)}
#define SPEC(label, index, handler, return_type, ...)                                                       \
    {.name = (label),                                                                              \
     .signature = {.abi = QA_NATIVE_ABI_CDECL_I386,                                                \
                   .parameters = PARAMS(__VA_ARGS__),                                              \
                   .parameter_count = sizeof(PARAMS(__VA_ARGS__)) / sizeof(qa_native_type),        \
                   .result = return_type},                                                         \
     .slot = (index), .dispatch = (handler)}
#define VARIADIC(label, index, handler, ...)                                                                \
    {.name = (label),                                                                              \
     .signature = {.abi = QA_NATIVE_ABI_CDECL_I386,                                                \
                   .parameters = PARAMS(__VA_ARGS__),                                              \
                   .parameter_count = sizeof(PARAMS(__VA_ARGS__)) / sizeof(qa_native_type),        \
                   .result = TYPE(QA_NATIVE_VOID),                                                 \
                   .variadic = true},                                                              \
     .slot = (index), .dispatch = (handler)}

