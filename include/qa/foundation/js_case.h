/*
 * JavaScript string case mapping and localeCompare where the C library's ASCII-only
 * tolower/toupper/strcasecmp/strcmp differ from the operation the TypeScript runs.
 * There is no corresponding .ts file: these are the JS built-ins themselves, matched
 * against Bun (JavaScriptCore + ICU), which runs the TS oracle.
 * tests/foundation/test_js_case.c pins them to values printed under bun.
 *
 * Two string representations exist in the port (docs/PORTING.md, Strings):
 *  - UTF-8 text: TS strings decoded with TextDecoder, and literals. The
 *    qa_js_to_lower_case/qa_js_to_upper_case/qa_js_equals_ignore_case family maps
 *    every code point as String.prototype.toLowerCase/toUpperCase do (Unicode
 *    simple and multi-code-point mappings, Final_Sigma), from tables generated by
 *    `bun tools/js_case_tables.js`. Bytes that are not valid UTF-8 are copied.
 *  - Quake byte strings: BinaryReader.fixedByteString maps each byte to the code
 *    point of the same value (Latin-1). toLowerCase of such a string stays in
 *    Latin-1: qa_js_latin1_lower folds A-Z and U+00C0-U+00DE except U+00D7.
 *
 * qa_js_locale_compare is a.localeCompare(b) with bun's default collator (en-US,
 * tertiary strength, punctuation not ignorable), exact for ASCII: controls other
 * than TAB..CR are ignorable, punctuation and symbols sort before digits before
 * letters, letters compare case-insensitively first and then lowercase before
 * uppercase. Non-ASCII code points are ordered after ASCII letters by code point,
 * which only approximates ICU's collation for them.
 * GPL-2.0-or-later.
 */
#ifndef QA_FOUNDATION_JS_CASE_H
#define QA_FOUNDATION_JS_CASE_H

#include <stdbool.h>
#include <stddef.h>

/** toLowerCase of one Latin-1 byte-string character (fixedByteString text). */
static inline unsigned char qa_js_latin1_lower(unsigned char c) {
  if ((c >= 'A' && c <= 'Z') || (c >= 0xc0 && c <= 0xde && c != 0xd7)) return (unsigned char)(c + 0x20);
  return c;
}
/** Malloc'd byte-string toLowerCase; NULL only on allocation failure. */
char *qa_js_latin1_to_lower_case(const char *text);
/** a.toLowerCase() === b.toLowerCase() for byte strings. */
bool qa_js_latin1_equals_ignore_case(const char *a, const char *b);

/** Malloc'd String.prototype.toLowerCase of UTF-8 text; NULL only on allocation failure. */
char *qa_js_to_lower_case(const char *text);
/** Malloc'd String.prototype.toUpperCase of UTF-8 text; NULL only on allocation failure. */
char *qa_js_to_upper_case(const char *text);
/** a.toLowerCase() === b.toLowerCase() for UTF-8 text. Aborts on allocation failure. */
bool qa_js_equals_ignore_case(const char *a, const char *b);
/** a.toLowerCase().endsWith(suffix.toLowerCase()) for UTF-8 text. */
bool qa_js_ends_with_ignore_case(const char *text, const char *suffix);
/** a.toLowerCase().startsWith(prefix.toLowerCase()) for UTF-8 text. */
bool qa_js_starts_with_ignore_case(const char *text, const char *prefix);

/** a.localeCompare(b): negative, zero or positive. */
int qa_js_locale_compare(const char *a, const char *b);
/** a.localeCompare(b, undefined, { sensitivity: "base" }). */
int qa_js_locale_compare_base(const char *a, const char *b);
/** a.localeCompare(b, "en", { numeric: true }). */
int qa_js_locale_compare_numeric(const char *a, const char *b);

#endif
