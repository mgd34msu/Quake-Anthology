// Generates src/foundation/js_case_tables.inc from the JS engine that runs the TS
// oracle: bun tools/js_case_tables.js > src/foundation/js_case_tables.inc
// Tables: simple lowercase/uppercase mappings, multi-code-point uppercase
// mappings, and the Cased / Case_Ignorable ranges used by the Final_Sigma rule.
const lower = [], upper = [], upperMulti = [], lowerMulti = [];
const hex = c => "0x" + c.toString(16);
for (let c = 0; c <= 0x10ffff; c++) {
  if (c >= 0xd800 && c <= 0xdfff) continue;
  if (c === 0x3a3) continue; // capital sigma: context rule in code
  const s = String.fromCodePoint(c);
  const l = [...s.toLowerCase()], u = [...s.toUpperCase()];
  if (l.length === 1 && l[0] !== s) lower.push([c, l[0].codePointAt(0)]);
  else if (l.length > 1) lowerMulti.push([c, l.map(x => x.codePointAt(0))]);
  if (u.length === 1 && u[0] !== s) upper.push([c, u[0].codePointAt(0)]);
  else if (u.length > 1) upperMulti.push([c, u.map(x => x.codePointAt(0))]);
}
const ranges = re => {
  const out = []; let start = -1;
  for (let c = 0; c <= 0x110000; c++) {
    const hit = c <= 0x10ffff && !(c >= 0xd800 && c <= 0xdfff) && re.test(String.fromCodePoint(c));
    if (hit && start < 0) start = c;
    if (!hit && start >= 0 && !(c >= 0xd800 && c <= 0xdfff)) { out.push([start, c - 1]); start = -1; }
  }
  return out;
};
const cased = ranges(/^\p{Cased}$/u), ignorable = ranges(/^\p{Case_Ignorable}$/u);
const lines = [];
lines.push(`/* Generated by bun tools/js_case_tables.js (bun ${Bun.version}); do not edit. */`);
const pairs = (name, list) => { lines.push(`static const js_case_pair ${name}[] = {`); for (let i = 0; i < list.length; i += 6) lines.push("  " + list.slice(i, i + 6).map(([a, b]) => `{${hex(a)}, ${hex(b)}}`).join(", ") + ","); lines.push("};"); };
const multis = (name, list) => { lines.push(`static const js_case_multi ${name}[] = {`); for (const [a, cps] of list) lines.push(`  {${hex(a)}, ${cps.length}, {${cps.map(hex).join(", ")}}},`); lines.push("};"); };
pairs("js_lower_pairs", lower); pairs("js_upper_pairs", upper);
multis("js_lower_multi", lowerMulti); multis("js_upper_multi", upperMulti);
pairs("js_cased_ranges", cased); pairs("js_case_ignorable_ranges", ignorable);
console.log(lines.join("\n"));
